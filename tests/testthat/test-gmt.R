test_that("GMT export preserves holes, identifiers, and geographic coordinates", {
  outer <- matrix(c(0,0, 4,0, 4,4, 0,4, 0,0), ncol=2, byrow=TRUE)
  hole <- matrix(c(1,1, 1,2, 2,2, 2,1, 1,1), ncol=2, byrow=TRUE)
  x <- sf::st_sf(area_code="001234", geometry=sf::st_sfc(sf::st_polygon(list(outer,hole)),crs=4326))
  path <- tempfile(fileext=".gmt")
  on.exit(unlink(path))
  write_gmt(sf::st_transform(x,3338),path)
  y <- sf::st_read(path,quiet=TRUE)
  expect_equal(y$area_code,"001234")
  expect_equal(length(sf::st_geometry(y)[[1]]),2L)
  expect_equal(sf::st_crs(y)$epsg,4326)
  expect_equal(as.numeric(sf::st_area(y)),as.numeric(sf::st_area(x)),tolerance=1e-6)
  expect_error(write_gmt(x,path),"File exists")
  expect_silent(write_gmt(x,path,overwrite=TRUE))
  expect_error(write_gmt(x,"test.txt"),"ending in .gmt")
  expect_error(write_gmt(sf::st_set_crs(x,NA),path),"known CRS")
})

test_that("GMT export splits dateline-crossing polygons", {
  ring <- matrix(c(179,50, -179,50, -179,52, 179,52, 179,50),ncol=2,byrow=TRUE)
  x <- sf::st_sf(area_code="crossing",geometry=sf::st_sfc(sf::st_polygon(list(ring)),crs=4326))
  path <- tempfile(fileext=".gmt")
  on.exit(unlink(path))
  write_gmt(x,path)
  y <- sf::st_read(path,quiet=TRUE)
  expect_equal(nrow(y),2L)
  expect_true(all(y$area_code=="crossing"))
  widths <- vapply(sf::st_geometry(y),function(g) diff(range(sf::st_coordinates(g)[,"X"])),numeric(1))
  expect_true(all(widths <= 1.01))
})
